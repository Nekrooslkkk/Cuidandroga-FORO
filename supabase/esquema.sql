create or replace function public.borrar_mensaje(p_id bigint, p_motivo text) returns void language plpgsql security definer set search_path = '' as $$
declare m record;
begin
  select ms.*, p.nombre into m from public.mensajes ms join public.perfiles p on p.id = ms.autor where ms.id = p_id;
  if m.id is null or not public.puede_moderar(m.autor) then raise exception 'No puedes borrar este mensaje.'; end if;
  if m.eliminado_por is not null then return; end if;
  insert into public.borrados (mensaje_id, texto) values (p_id, m.texto);
  update public.mensajes set texto = '', eliminado_por = auth.uid(), eliminado_motivo = p_motivo, eliminado_en = now() where id = p_id;
  update public.denuncias set estado = 'resuelta' where mensaje_id = p_id and estado = 'pendiente';
  perform public.notificar(m.autor, 'borrado', jsonb_build_object('foro', m.foro_id, 'por', auth.uid(),
    'cita', case when char_length(m.texto) > 90 then left(m.texto, 90) || '…' else m.texto end));
  perform public.anotar('Borró un mensaje de ' || m.nombre || ' en el Foro #' || m.foro_id, p_motivo);
end $$;

