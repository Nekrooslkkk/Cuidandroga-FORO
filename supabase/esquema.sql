create or replace function public.al_responder() returns trigger language plpgsql security definer set search_path = '' as $$
declare f record;
begin
  select * into f from public.foros where id = new.foro_id;
  -- autor del foro
  if f.autor <> new.autor and exists (select 1 from auth.users u where u.id = f.autor) then perform public.notificar(f.autor, 'respuesta', jsonb_build_object('de', new.autor, 'foro', new.foro_id)); end if;
  -- quienes participan (si lo tienen activado)
  insert into public.notificaciones (para, tipo, datos)
  select distinct m.autor, 'respuesta', jsonb_build_object('de', new.autor, 'foro', new.foro_id)
  from public.mensajes m join public.privados v on v.id = m.autor
  where m.foro_id = new.foro_id and m.autor not in (new.autor, f.autor) and v.avisar_participo
    and exists (select 1 from auth.users u where u.id = m.autor);
  -- quienes quieren saber de todos los foros
  insert into public.notificaciones (para, tipo, datos)
  select v.id, 'foro', jsonb_build_object('de', new.autor, 'foro', new.foro_id)
  from public.privados v
  where v.avisar_todos and v.id not in (new.autor, f.autor)
    and not exists (select 1 from public.mensajes m where m.foro_id = new.foro_id and m.autor = v.id)
    and exists (select 1 from auth.users u where u.id = v.id);
  return new;
end $$;
create trigger al_responder after insert on public.mensajes for each row execute function public.al_responder();

create or replace function public.al_dar_like() returns trigger language plpgsql security definer set search_path = '' as $$
declare m record;
begin
  select ms.autor, ms.foro_id, v.avisar_likes into m from public.mensajes ms left join public.privados v on v.id = ms.autor where ms.id = new.mensaje_id;
  if m.autor <> new.usuario and coalesce(m.avisar_likes, true) and exists (select 1 from auth.users u where u.id = m.autor) then
    perform public.notificar(m.autor, 'like', jsonb_build_object('de', new.usuario, 'foro', m.foro_id));
  end if;
  return new;
end $$;
create trigger al_dar_like after insert on public.likes for each row execute function public.al_dar_like();

