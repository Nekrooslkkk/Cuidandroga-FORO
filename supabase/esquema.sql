create table public.perfiles (
  id uuid primary key,
  nombre text not null,
  nombre_norm text not null unique,
  rol text not null default 'usuario' check (rol in ('usuario','moderador','admin')),
  av jsonb not null default '{"t":145,"f":0,"a":0}' check (octet_length(av::text) < 90000),
  pub_estudios boolean not null default true,
  pub_edad boolean not null default true,
  suspendido boolean not null default false,
  debe_cambiar_nombre boolean not null default false,
  debe_cambiar_clave boolean not null default false,
  bot_activo boolean not null default false,
  ultima_vez timestamptz,
  creado timestamptz not null default now()
);
create table public.privados (
  id uuid primary key references public.perfiles(id) on delete cascade,
  correo text unique,
  edad_modo text check (edad_modo in ('fecha','anio')),
  nacimiento date,
  anio int,
  edad_registro int,
  anio_registro int,
  sexo text, genero text,
  estudia boolean, uni text, carrera text,
  trabaja boolean, ocupacion text,
  encuesta_final boolean,
  avisar_todos boolean not null default false,
  avisar_participo boolean not null default true,
  avisar_likes boolean not null default true,
  folleto_visto boolean not null default false
);
create table public.foros (
  id bigint generated by default as identity primary key,
  autor uuid not null references public.perfiles(id) on delete cascade,
  titulo text not null check (char_length(titulo) between 1 and 60),
  pregunta text not null check (char_length(pregunta) between 1 and 160),
  destacado boolean not null default false,
  enc_pregunta text,
  enc_opciones text[] check (enc_opciones is null or array_length(enc_opciones, 1) between 2 and 3),
  enc_publica boolean not null default false,
  creado timestamptz not null default now()
);
create table public.mensajes (
  id bigint generated by default as identity primary key,
  foro_id bigint not null references public.foros(id) on delete cascade,
  autor uuid not null references public.perfiles(id) on delete cascade,
  texto text not null check (char_length(texto) <= 5000),
  likes_base int not null default 0,
  creado timestamptz not null default now(),
  eliminado_por uuid references public.perfiles(id),
  eliminado_motivo text,
  eliminado_en timestamptz
);
create table public.borrados (mensaje_id bigint primary key references public.mensajes(id) on delete cascade, texto text not null);
create table public.likes (
  mensaje_id bigint references public.mensajes(id) on delete cascade,
  usuario uuid references public.perfiles(id) on delete cascade,
  creado timestamptz not null default now(),
  primary key (mensaje_id, usuario)
);
create table public.votos (
  foro_id bigint references public.foros(id) on delete cascade,
  usuario uuid references public.perfiles(id) on delete cascade,
  opcion int not null check (opcion between 0 and 2),
  primary key (foro_id, usuario)
);
create table public.denuncias (
  id bigint generated by default as identity primary key,
  mensaje_id bigint not null references public.mensajes(id) on delete cascade,
  por uuid not null references public.perfiles(id) on delete cascade,
  motivo text not null,
  estado text not null default 'pendiente' check (estado in ('pendiente','resuelta','descartada')),
  creado timestamptz not null default now(),
  unique (mensaje_id, por)
);
create table public.notificaciones (
  id bigint generated by default as identity primary key,
  para uuid not null references public.perfiles(id) on delete cascade,
  tipo text not null,
  datos jsonb not null default '{}',
  creado timestamptz not null default now()
);
create table public.avisos (
  id bigint generated by default as identity primary key,
  autor uuid not null references public.perfiles(id),
  titulo text not null, texto text not null,
  boton text check (boton in ('folleto','encuesta')),
  fijo boolean not null default false,
  foro_id bigint references public.foros(id) on delete cascade,
  creado timestamptz not null default now()
);
create table public.avisos_cerrados (
  usuario uuid references public.perfiles(id) on delete cascade,
  aviso_id text not null,
  primary key (usuario, aviso_id)
);
create table public.solicitudes (
  id bigint generated by default as identity primary key,
  usuario uuid not null references public.perfiles(id) on delete cascade,
  campo text not null check (campo in ('edad','uni','carrera','ocupacion','sexo','genero')),
  valor text not null,
  estado text not null default 'pendiente' check (estado in ('pendiente','aprobada','rechazada')),
  creado timestamptz not null default now()
);
create table public.registro_mod (
  id bigint generated by default as identity primary key,
  por uuid references public.perfiles(id) on delete set null,
  accion text not null, motivo text,
  creado timestamptz not null default now()
);
create table public.recuperaciones (
  id bigint generated by default as identity primary key,
  correo text not null,
  estado text not null default 'pendiente',
  creado timestamptz not null default now()
);
create index on public.mensajes (foro_id);
create index on public.notificaciones (para);

