create view public.publicos as
select p.id, p.nombre, p.rol, p.av, p.suspendido, p.pub_estudios, p.pub_edad, p.creado,
  (p.bot_activo or coalesce(p.ultima_vez > now() - interval '3 minutes', false)) as en_linea,
  case when p.pub_estudios and v.estudia then v.uni end as uni,
  case when p.pub_estudios and v.estudia then v.carrera end as carrera,
  case when p.pub_estudios and not coalesce(v.estudia, false) and v.trabaja then v.ocupacion end as ocupacion,
  case when p.pub_edad then
    case when v.edad_modo = 'fecha' then extract(year from age((now() at time zone 'America/Santiago')::date, v.nacimiento))::int
         else v.edad_registro + (extract(year from now())::int - v.anio_registro) end
  end as edad
from public.perfiles p left join public.privados v on v.id = p.id;

