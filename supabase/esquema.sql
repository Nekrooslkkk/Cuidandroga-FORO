create or replace function public.normalizar(t text) returns text language sql immutable set search_path = '' as $$
  select lower(translate(btrim(regexp_replace(coalesce(t,''), '^@', '')), 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun'))
$$;
create or replace function public.mi_rol() returns text language sql stable security definer set search_path = '' as $$
  select rol from public.perfiles where id = auth.uid()
$$;
create or replace function public.es_mod() returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select rol in ('moderador','admin') from public.perfiles where id = auth.uid()), false)
$$;
create or replace function public.es_admin() returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select rol = 'admin' from public.perfiles where id = auth.uid()), false)
$$;
create or replace function public.activo() returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.perfiles where id = auth.uid() and not suspendido)
$$;
create or replace function public.anotar(p_accion text, p_motivo text default null) returns void language sql security definer set search_path = '' as $$
  insert into public.registro_mod (por, accion, motivo) values (auth.uid(), p_accion, p_motivo)
$$;
create or replace function public.notificar(p_para uuid, p_tipo text, p_datos jsonb default '{}') returns void language sql security definer set search_path = '' as $$
  insert into public.notificaciones (para, tipo, datos) select p_para, p_tipo, p_datos where p_para is not null
$$;
create or replace function public.clave_fuerte(c text) returns boolean language sql immutable set search_path = '' as $$
  select char_length(c) >= 8 and c ~ '[A-ZÁÉÍÓÚÑ]' and c ~ '[a-záéíóúñ]' and c ~ '[0-9]' and c ~ '[^A-Za-zÁÉÍÓÚÑáéíóúñ0-9]'
$$;
create or replace function public.correo_login_de(p_id uuid) returns text language sql immutable set search_path = '' as $$
  select 'u' || replace(p_id::text, '-', '') || '@usuarios.cuidandroga.invalid'
$$;

/* crea la cuenta de acceso ya confirmada (sin mandar correos) */
create or replace function public.crear_acceso(p_id uuid, p_correo text, p_clave text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change)
  values ('00000000-0000-0000-0000-000000000000', p_id, 'authenticated', 'authenticated', p_correo,
    extensions.crypt(p_clave, extensions.gen_salt('bf', 10)), now(),
    '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), p_id, p_id::text, 'email',
    jsonb_build_object('sub', p_id::text, 'email', p_correo, 'email_verified', true), now(), now(), now());
end $$;
revoke execute on function public.crear_acceso(uuid, text, text) from public, anon, authenticated;

