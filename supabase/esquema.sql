create or replace function public.resolver_solicitud(p_id bigint, p_ok boolean) returns void language plpgsql security definer set search_path = '' as $$
declare s record; v_hoy date := (now() at time zone 'America/Santiago')::date;
begin
  if not public.es_mod() then raise exception 'Solo moderación.'; end if;
  select * into s from public.solicitudes where id = p_id and estado = 'pendiente';
  if s.id is null then return; end if;
  update public.solicitudes set estado = case when p_ok then 'aprobada' else 'rechazada' end where id = p_id;
  if p_ok then
    if s.campo = 'edad' then update public.privados set edad_modo = 'anio', edad_registro = s.valor::int, anio_registro = extract(year from v_hoy)::int,
        anio = extract(year from v_hoy)::int - s.valor::int, nacimiento = null where id = s.usuario;
    elsif s.campo = 'uni' then update public.privados set uni = s.valor, estudia = true, trabaja = false, carrera = coalesce(carrera, 'periodismo') where id = s.usuario;
    elsif s.campo = 'carrera' then update public.privados set carrera = s.valor, estudia = true, trabaja = false, uni = coalesce(uni, 'uch') where id = s.usuario;
    elsif s.campo = 'ocupacion' then update public.privados set ocupacion = s.valor, trabaja = true, estudia = false where id = s.usuario;
    elsif s.campo = 'sexo' then update public.privados set sexo = s.valor where id = s.usuario;
    elsif s.campo = 'genero' then update public.privados set genero = s.valor where id = s.usuario;
    end if;
  end if;
  perform public.notificar(s.usuario, 'solicitudRes', jsonb_build_object('ok', p_ok));
  perform public.anotar(case when p_ok then 'Aprobó' else 'Rechazó' end || ' un cambio de ' || s.campo || ' de ' || (select nombre from public.perfiles where id = s.usuario));
end $$;

