create or replace function public.nombre_libre(p_nombre text) returns boolean language sql stable security definer set search_path = '' as $$
  select not exists (select 1 from public.perfiles where nombre_norm = public.normalizar(p_nombre))
$$;
create or replace function public.correo_libre(p_correo text) returns boolean language sql stable security definer set search_path = '' as $$
  select not exists (select 1 from public.privados where lower(correo) = lower(btrim(p_correo)))
$$;
create or replace function public.correo_login(p_nombre text) returns text language sql stable security definer set search_path = '' as $$
  select public.correo_login_de(id) from public.perfiles where nombre_norm = public.normalizar(p_nombre)
$$;

create or replace function public.registrar(d jsonb) returns text language plpgsql security definer set search_path = '' as $$
declare
  v_id uuid := gen_random_uuid();
  v_nombre text := '@' || regexp_replace(btrim(d->>'nombre'), '^@', '');
  v_hoy date := (now() at time zone 'America/Santiago')::date;
  v_edad int;
begin
  if v_nombre !~ '^@[A-Za-zÁÉÍÓÚÑáéíóúñ0-9._]{3,20}$' then raise exception 'NOMBRE: Usa entre 3 y 20 letras, números, puntos o guiones bajos.'; end if;
  if not public.nombre_libre(v_nombre) then raise exception 'NOMBRE: Ese nombre ya está ocupado.'; end if;
  if coalesce(d->>'correo','') !~ '^[^\s@]+@[^\s@]+\.[^\s@]{2,}$' then raise exception 'CORREO: Escribe un correo válido.'; end if;
  if not public.correo_libre(d->>'correo') then raise exception 'CORREO: Ya hay una cuenta con ese correo.'; end if;
  if not public.clave_fuerte(d->>'clave') then raise exception 'CLAVE: La contraseña no es lo bastante fuerte.'; end if;
  if d->>'edadModo' = 'fecha' then
    if (d->>'nacimiento')::date > (v_hoy - interval '18 years')::date then raise exception 'EDAD: Tienes que tener 18 años o más para registrarte.'; end if;
    v_edad := extract(year from age(v_hoy, (d->>'nacimiento')::date))::int;
  elsif d->>'edadModo' = 'anio' then
    v_edad := extract(year from v_hoy)::int - (d->>'anio')::int - case when (d->>'cumplio')::boolean then 0 else 1 end;
    if v_edad < 18 then raise exception 'EDAD: Tienes que tener 18 años o más para registrarte.'; end if;
  else raise exception 'EDAD: Falta tu edad.'; end if;
  if (d->>'estudia')::boolean and (coalesce(d->>'uni','') not in ('uch','uc','unab') or coalesce(d->>'carrera','') not in ('periodismo','derecho','informatica')) then
    raise exception 'ESTUDIOS: Elige tu universidad y tu carrera.'; end if;

  perform public.crear_acceso(v_id, public.correo_login_de(v_id), d->>'clave');
  insert into public.perfiles (id, nombre, nombre_norm, av, pub_estudios, pub_edad, ultima_vez)
  values (v_id, v_nombre, public.normalizar(v_nombre), coalesce(d->'av', '{"t":145,"f":0,"a":0}'),
    coalesce((d->>'pubEstudios')::boolean, true), coalesce((d->>'pubEdad')::boolean, true), now());
  insert into public.privados (id, correo, edad_modo, nacimiento, anio, edad_registro, anio_registro, sexo, genero,
    estudia, uni, carrera, trabaja, ocupacion, encuesta_final)
  values (v_id, lower(btrim(d->>'correo')), d->>'edadModo',
    case when d->>'edadModo' = 'fecha' then (d->>'nacimiento')::date end,
    case when d->>'edadModo' = 'anio' then (d->>'anio')::int end,
    v_edad, extract(year from v_hoy)::int, d->>'sexo', d->>'genero',
    (d->>'estudia')::boolean,
    case when (d->>'estudia')::boolean then d->>'uni' end,
    case when (d->>'estudia')::boolean then d->>'carrera' end,
    case when (d->>'estudia')::boolean then false else coalesce((d->>'trabaja')::boolean, false) end,
    case when not (d->>'estudia')::boolean and (d->>'trabaja')::boolean then d->>'ocupacion' end,
    (d->>'encuestaFinal')::boolean);
  perform public.notificar(v_id, 'bienvenida');
  insert into public.notificaciones (para, tipo, datos) select id, 'nuevo', jsonb_build_object('de', v_id) from public.perfiles where rol = 'admin';
  return public.correo_login_de(v_id);
end $$;

create or replace function public.cambiar_clave(p_actual text, p_nueva text) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from auth.users where id = auth.uid() and encrypted_password = extensions.crypt(p_actual, encrypted_password)) then
    raise exception 'ACTUAL: La contraseña actual no es correcta.'; end if;
  if not public.clave_fuerte(p_nueva) then raise exception 'NUEVA: La contraseña nueva no es lo bastante fuerte.'; end if;
  update auth.users set encrypted_password = extensions.crypt(p_nueva, extensions.gen_salt('bf', 10)), updated_at = now() where id = auth.uid();
  update public.perfiles set debe_cambiar_clave = false where id = auth.uid();
end $$;

create or replace function public.cambiar_nombre(p_nombre text) returns void language plpgsql security definer set search_path = '' as $$
declare v_nombre text := '@' || regexp_replace(btrim(p_nombre), '^@', '');
begin
  if v_nombre !~ '^@[A-Za-zÁÉÍÓÚÑáéíóúñ0-9._]{3,20}$' then raise exception 'NOMBRE: Usa entre 3 y 20 letras, números, puntos o guiones bajos.'; end if;
  if exists (select 1 from public.perfiles where nombre_norm = public.normalizar(v_nombre) and id <> auth.uid()) then raise exception 'NOMBRE: Ese nombre ya está ocupado.'; end if;
